#!/usr/bin/env python
"""Build the dexsuite PyPI distribution (wheel + sdist) into dist/.

    python scripts/packaging/build.py

The package carries every module and config and the assets of scripts/packaging/assets.txt: every file a shipped task
or robot loads, and the floor textures (regenerate the list with scripts/packaging/trace_assets.py after adding a task
or a robot). The object models no task loads stay in the repository, which keeps the wheel under
PyPI's 100 MB file limit. Textures are stored at most 1024 px (the cameras render at 224 px); the build checks it.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tomllib
import zipfile
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
MODELS = REPO / "dexsuite" / "models"
DIST = REPO / "dist"
LIMIT_MB = 100.0
MAX_TEXTURE_PX = 1024
NOTICE_NAMES = re.compile(r"^(LICENSE|LICENCE|COPYING|NOTICE|ATTRIBUTION|README)", re.I)


def read_list(name: str) -> list[str]:
    return [ln.strip() for ln in (HERE / name).read_text().splitlines() if ln.strip()]


def notices(files: list[str]) -> list[str]:
    """License and readme files of every model folder a list touches (models/<kind>/<name>/ and its subfolders)."""
    roots = {Path(*Path(f).parts[:3]) if Path(f).parts[0] == "objects" else Path(*Path(f).parts[:2]) for f in files}
    out = set()
    for r in roots:
        for p in (MODELS / r).rglob("*"):
            if p.is_file() and NOTICE_NAMES.match(p.name) and p.suffix.lower() not in (".py",):
                out.add(str(p.relative_to(MODELS)))
    return sorted(out - set(files))


def write_manifest(assets: list[str]) -> None:
    lines = ["# Generated by scripts/packaging/build.py from scripts/packaging/assets.txt; do not edit by hand.",
             "# The dexsuite wheel carries every module and config, every robot and the assets of every task.",
             "prune scripts", "prune tests", "prune docs",
             "include README.md CONTRIBUTING.md requirements.txt LICENSE THIRD_PARTY_LICENSES.md",
             "include scripts/packaging/README_pypi.md",
             "recursive-include dexsuite *.yaml *.yml", ""]
    lines += [f"include dexsuite/models/{f}" for f in assets + notices(assets)]
    (REPO / "MANIFEST.in").write_text("\n".join(lines) + "\n")


def main() -> None:
    version = tomllib.loads((REPO / "pyproject.toml").read_text())["project"]["version"]
    init = re.search(r'^__version__ = "([^"]+)"', (REPO / "dexsuite/__init__.py").read_text(), re.M)
    if not init or init.group(1) != version:
        raise SystemExit(f"dexsuite/__init__.py __version__ does not match pyproject version {version}")
    assets = read_list("assets.txt")
    missing = [f for f in assets if not (MODELS / f).is_file()]
    if missing:
        raise SystemExit(f"{len(missing)} listed assets are missing, e.g. {missing[:3]}")
    big = [f for f in assets if Path(f).suffix.lower() in (".png", ".jpg", ".jpeg")
           and max(Image.open(MODELS / f).size) > MAX_TEXTURE_PX]
    if big:
        raise SystemExit(f"{len(big)} textures are over {MAX_TEXTURE_PX} px, e.g. {big[:3]}; scale them down")
    # setuptools reuses build/: a file deleted from the repository would still ship
    for stale in [DIST, REPO / "build", *REPO.glob("*.egg-info")]:
        shutil.rmtree(stale, ignore_errors=True)
    DIST.mkdir()
    write_manifest(assets)
    subprocess.run([sys.executable, "-m", "build", "--sdist", "--wheel", "--outdir", str(DIST)], cwd=REPO, check=True)
    wheel = next(DIST.glob(f"dexsuite-{version}-*.whl"))
    names = set(zipfile.ZipFile(wheel).namelist())
    absent = [f for f in assets if f"dexsuite/models/{f}" not in names]
    if absent:
        raise SystemExit(f"{len(absent)} listed assets are missing from the wheel, e.g. {absent[:3]}")
    listed = {f"dexsuite/models/{f}" for f in assets + notices(assets)}
    unlisted = [n for n in names if n.startswith("dexsuite/models/") and not n.endswith((".py", ".yaml", ".yml", "/"))
                and n not in listed]
    if unlisted:
        raise SystemExit(f"{len(unlisted)} model files not in assets.txt ended up in the wheel, e.g. {unlisted[:3]}")
    for p in sorted(DIST.iterdir()):
        mb = p.stat().st_size / 1e6
        print(f"{p.name:48s} {mb:7.1f} MB{'   OVER THE PYPI LIMIT' if mb > LIMIT_MB else ''}")
    if any(p.stat().st_size / 1e6 > LIMIT_MB for p in DIST.iterdir()):
        raise SystemExit("a distribution is over PyPI's file size limit")
    print(f"dexsuite wheel: {len(names)} files")


if __name__ == "__main__":
    main()
