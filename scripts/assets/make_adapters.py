#!/usr/bin/env python
"""Rebuild the adapter files of arms whose end-effectors were mounted at the wrong angle.

An adapter places a mount on the arm's end_link and the end-effector on the mount. The entries for these arms were
copied from another arm without accounting for where each arm's flange is, so grippers ended up sideways or pointing
into the wrist. This script derives them from a reference arm whose mounts are right:

    mount_new = F_arm * inverse(F_ref) * mount_ref

where F is the flange (the tool attachment frame, +z pointing out of the flange) expressed in the arm's end_link frame,
read from the attachment site of each model. The end-effector entries (gripper_pos, gripper_quat, geometry) are copied
from the reference unchanged, so every end-effector sits on the flange exactly as it does on the reference arm.

    python scripts/assets/make_adapters.py          # rewrites the adapter files listed in ARMS
"""
from __future__ import annotations

import math
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2] / "dexsuite/models/manipulators"


def qmul(a, b):
    w1, x1, y1, z1 = a
    w2, x2, y2, z2 = b
    return (w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2, w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2,
            w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2, w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2)


def qconj(q):
    return (q[0], -q[1], -q[2], -q[3])


def qrot(q, v):
    w, x, y, z = qmul(qmul(q, (0.0, *v)), qconj(q))
    return (x, y, z)


def tmul(a, b):
    """(p, q) transforms: a * b."""
    pa, qa = a
    pb, qb = b
    r = qrot(qa, pb)
    return ((pa[0] + r[0], pa[1] + r[1], pa[2] + r[2]), qmul(qa, qb))


def tinv(a):
    p, q = a
    qi = qconj(q)
    r = qrot(qi, p)
    return ((-r[0], -r[1], -r[2]), qi)


def axis_angle(axis, deg):
    s = math.sin(math.radians(deg) / 2)
    return (math.cos(math.radians(deg) / 2), axis[0] * s, axis[1] * s, axis[2] * s)


I = (1.0, 0.0, 0.0, 0.0)
# Flange frames in each arm's end_link frame (+z out of the flange), from the models' attachment sites.
GEN3 = ((0.0, 0.0, -0.061525), (0.0, 1.0, 0.0, 0.0))     # bracelet_link pinch_site: the flange faces -z
FRANKA = ((0.0, 0.0, 0.0), I)                            # end_link "attachment" is the flange itself
ARMS = {
    # arm: (reference adapters, reference flange, this arm's flange, end-effectors to keep)
    "kuka": ("gen3", GEN3, ((0.0, 0.0, 0.045), I), None),                                  # link7 attachment_site
    "sawyer": ("gen3", GEN3, ((0.0, 0.0, 0.0245), (0.0, 0.0, 0.0, 1.0)), None),            # right_l6 attachment_site
    "lite6": ("gen3", GEN3, ((0.0, 0.0, 0.0), I), None),                                   # link6 attachment_site
    "z1": ("gen3", GEN3, ((0.051, 0.0, 0.0), axis_angle((0, 1, 0), 90)), None),            # link06 end face (mesh ends at x = 0.051); joint6 turns about +x
    "link6": ("gen3", GEN3, ((0.0, 0.0, 0.0), I), None),                                   # end_effector_link (tool0)
    # FR3 has no attachment body: its end_link is fr3_link7, the Panda's attachment sits 0.107 m out, turned 135 deg
    "franka_fr3": ("franka", FRANKA, ((0.0, 0.0, 0.107), (0.3826834, 0.0, 0.0, 0.9238795)), None),
}
HEADER = """# Generated by scripts/assets/make_adapters.py from {ref}_adapters.yaml: every end-effector sits on this arm's
# flange as it does on the {ref}. mount = flange(this arm) * inverse(flange({ref})) * mount({ref}).
# Edit the reference or the flange in the script and re-run, rather than editing this file by hand.

"""


def fmt(v):
    return "[" + ", ".join(f"{x:.7f}".rstrip("0").rstrip(".") if abs(x) > 1e-12 else "0.0" for x in v) + "]"


def main():
    for arm, (ref, f_ref, f_arm, keep) in ARMS.items():
        src = ROOT / ref / f"{ref}_adapters.yaml"
        entries = yaml.safe_load(src.read_text())
        out = [HEADER.format(ref=ref)]
        for key, e in entries.items():
            if keep and key not in keep:
                continue
            m = (tuple(e["mount_pos"]), tuple(e["mount_quat"]))
            p, q = tmul(tmul(f_arm, tinv(f_ref)), m)
            n = math.sqrt(sum(c * c for c in q))
            q = tuple(c / n for c in q)
            geom = dict(e.get("geometry") or {})
            if "file" in geom and ref != arm:                       # mesh mounts: keep pointing at the reference's file
                geom["file"] = f"../{ref}/{geom['file']}"
            lines = [f"{key}:", f"  mount_type : {e['mount_type']}", f"  mount_pos  : {fmt(p)}", f"  mount_quat : {fmt(q)}"]
            if geom:
                lines.append("  geometry   :")
                lines += [f"    {k} : {v}" for k, v in geom.items()]
            lines += [f"  gripper_pos  : {fmt(e['gripper_pos'])}", f"  gripper_quat : {fmt(e['gripper_quat'])}", ""]
            out.append("\n".join(lines) + "\n")
        dst = ROOT / arm / f"{arm}_adapters.yaml"
        dst.write_text("".join(out).rstrip("\n") + "\n")
        print(f"{arm}: {len(entries)} end-effectors from {ref}")


if __name__ == "__main__":
    main()
